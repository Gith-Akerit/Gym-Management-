(function (root) {
  'use strict';

  /**
   * 038541029 → 038-541-029 · 0812345678 → 081-234-5678
   * อะไรที่ไม่เข้ารูปเบอร์ในประเทศไทยคืนค่าเดิมไม่แตะ ดีกว่าขีดผิดที่
   * แล้วคนกดโทรออกไม่ติด
   */
  function formatPhone(value) {
    if (!value) return null;
    return String(value).replace(/^(0\d{1,2})(\d{3})(\d{3,4})$/, '$1-$2-$3');
  }

  var API = { formatPhone: formatPhone };
  if (typeof module !== 'undefined' && module.exports) module.exports = API;
  root.Phone = API;
})(typeof window !== 'undefined' ? window : globalThis);
